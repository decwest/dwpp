def _format_csv(value: object) -> object:
    if isinstance(value, (float, np.floating)):
        return f"{float(value):.9g}"
    return value


def write_csv(
    rows: Sequence[dict[str, object]],
    csv_path: Path,
    *,
    lineterminator: str = "\n",
) -> None:
    if not rows:
        raise ValueError(f"Cannot write an empty table: {csv_path}")
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    fields = list(rows[0])
    with csv_path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, lineterminator=lineterminator)
        writer.writeheader()
        for row in rows:
            writer.writerow({key: _format_csv(row[key]) for key in fields})


def write_table(rows: Sequence[dict[str, object]], csv_path: Path) -> None:
    # Preserve the legacy raw-table CSV format used by smoke and practical bounds.
    write_csv(rows, csv_path, lineterminator="\r\n")
    write_latex(rows, csv_path.with_suffix(".tex"))


def _latex_escape(value: object) -> str:
    text = _format_csv(value)
    return str(text).replace("_", r"\_").replace("%", r"\%")


def write_latex(rows: Sequence[dict[str, object]], tex_path: Path) -> None:
    fields = list(rows[0])
    alignment = "l" + "r" * (len(fields) - 1)
    lines = [
        "% Auto-generated by scripts/revision/run_studies.py",
        rf"\begin{{tabular}}{{{alignment}}}",
        r"\toprule",
        " & ".join(_latex_escape(field) for field in fields) + r" \\",
        r"\midrule",
    ]
    lines.extend(" & ".join(_latex_escape(row[field]) for field in fields) + r" \\" for row in rows)
    lines.extend((r"\bottomrule", r"\end{tabular}", ""))
    tex_path.write_text("\n".join(lines), encoding="utf-8")


def _sig(value: object) -> str:
    return f"{float(value):.3g}"


# Manuscript display precision, matched to the real-robot tables:
# violation 1 decimal, errors 2 decimals, travel time 1 decimal.
_METRIC_DECIMALS = {
    "violation_ratio": 1,
    "mean_error": 2,
    "max_error": 2,
    "travel_time": 1,
}


def _dec(value: object, places: int) -> str:
    return f"{float(value):.{places}f}"


def _param(value: object) -> str:
    """Swept-parameter display: significant digits, but never bare integers."""
    text = _sig(value)
    return text if "." in text else f"{text}.0"


def _latex_display(value: object) -> str:
    return _latex_escape(value).replace(" +- ", r" $\pm$ ")


def _write_manuscript_latex(
    tex_path: Path,
    *,
    caption: str,
    alignment: str,
    header_lines: Sequence[str],
    body_rows: Sequence[Sequence[object]],
) -> None:
    lines = [
        "% Auto-generated by scripts/revision/run_studies.py",
        r"\begin{table}[t]",
        r"\centering",
        rf"\caption{{{caption}}}",
        rf"\begin{{tabular}}{{{alignment}}}",
        r"\toprule",
        *header_lines,
        r"\midrule",
    ]
    lines.extend(" & ".join(_latex_display(value) for value in row) + r" \\" for row in body_rows)
    lines.extend((r"\bottomrule", r"\end{tabular}", r"\end{table}", ""))
    tex_path.write_text("\n".join(lines), encoding="utf-8")


def _write_app_table(rows: Sequence[dict[str, object]], out: Path) -> None:
    table_rows: list[dict[str, object]] = []
    for value in sorted({float(row["lookahead_time"]) for row in rows}):
        app = _filter(rows, arm="APP", lookahead_time=value)[0]
        dynamic = _filter(rows, arm="APP+DW", lookahead_time=value)[0]
        table_rows.append(
            {
                "l_t [s]": _dec(value, 1),
                "APP Violation [%]": _dec(app["violation_ratio"], 1),
                "APP Mean err. [m]": _dec(app["mean_error"], 2),
                "APP Max err. [m]": _dec(app["max_error"], 2),
                "APP Time [s]": _dec(app["travel_time"], 1),
                "APP+DW Violation [%]": _dec(dynamic["violation_ratio"], 1),
                "APP+DW Mean err. [m]": _dec(dynamic["mean_error"], 2),
                "APP+DW Max err. [m]": _dec(dynamic["max_error"], 2),
                "APP+DW Time [s]": _dec(dynamic["travel_time"], 1),
            }
        )
    write_csv(table_rows, out / "app_table.csv")
    _write_manuscript_latex(
        out / "app_table.tex",
        caption=r"PathC adaptive-lookahead results.",
        alignment="rrrrrrrrr",
        header_lines=(
            r" & \multicolumn{4}{c}{APP} & \multicolumn{4}{c}{APP+DW} \\",
            r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
            r"$l_t$ [s] & Violation [\%] & Mean err. [m] & Max err. [m] & Time [s] & Violation [\%] & Mean err. [m] & Max err. [m] & Time [s] \\",
        ),
        body_rows=[tuple(row.values()) for row in table_rows],
    )


